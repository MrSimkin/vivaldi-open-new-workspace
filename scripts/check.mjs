import assert from "node:assert/strict";
import {readFileSync,readdirSync,existsSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {join} from "node:path";
import {execFileSync} from "node:child_process";
import {createHash} from "node:crypto";
const root=fileURLToPath(new URL("../",import.meta.url)), ext=join(root,"extension");
const manifest=JSON.parse(readFileSync(join(ext,"manifest.json"),"utf8"));
const pkg=JSON.parse(readFileSync(join(root,"package.json"),"utf8"));
assert.equal(manifest.manifest_version,3);assert.equal(manifest.name,"Open New Workspace");assert.equal(manifest.version,pkg.version);
assert.deepEqual(manifest.permissions,["storage"]);assert.deepEqual(manifest.background,{service_worker:"worker.js",type:"module"});
for(const k of ["host_permissions","optional_permissions","optional_host_permissions","content_scripts","externally_connectable"])assert.equal(manifest[k],undefined);
const id=createHash("sha256").update(Buffer.from(manifest.key,"base64")).digest("hex").slice(0,32).replace(/[0-9a-f]/g,x=>String.fromCharCode(97+parseInt(x,16)));
assert.equal(id,"poebajclpmcacjgkdbkjfjbngmagakbe");
const bridge=join(root,"bridge","onw-workspace-bridge.js");
assert.ok(readFileSync(bridge,"utf8").includes(id));
const html=readFileSync(join(ext,"popup.html"),"utf8");
for(const [,p] of html.matchAll(/(?:src|href)="([^"]+)"/g)){assert.ok(!/^(?:[a-z]+:|\/|\.\.)/i.test(p));assert.ok(existsSync(join(ext,p)));}
for(const p of [...readdirSync(ext).filter(x=>x.endsWith(".js")).map(x=>join(ext,x)),bridge])execFileSync(process.execPath,["--check",p],{stdio:"inherit"});
console.log("ONW check passed.");
